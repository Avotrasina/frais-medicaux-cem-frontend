import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const HEADER = "// AUTO-GENERATED by scripts/split-api-types.mjs - DO NOT EDIT";
const DOMAIN_OVERRIDES = {
	"actes": "acte",
	"agent-categories": "categorie-agent",
	"agent-families": "famille-agent",
	"agents": "agent",
	"attestations": "attestation",
	"beneficiaries": "beneficiaire",
	"categories-actes": "categorie-acte",
	"factures": "facture",
	"locations": "lieu",
	"organizational-structures": "structure-organisationnelle",
	"plafonds": "plafond",
	"provider-categories": "categorie-prestataire",
	"providers": "prestataire",
	"regles-prise-en-charge": "regle-prise-en-charge",
	"suivis": "suivi",
	"utilisateurs": "utilisateur",
};
const DEFAULT_DOMAIN = "default";
const SCHEMA_REFERENCE = /components\s*\[\s*["']schemas["']\s*\]\s*\[\s*["']([^"']+)["']\s*\]/g;
const OPERATION_REFERENCE = /operations\s*\[\s*["']([^"']+)["']\s*\]/g;
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(scriptDirectory, "..");
const apiDirectory = path.join(rootDirectory, "src", "api");
const schemaPath = path.join(apiDirectory, "schema.d.ts");
const domainsPath = path.join(apiDirectory, "domains");
const checkOnly = process.argv.includes("--check");

function compareStrings(left, right) {
	return left < right ? -1 : left > right ? 1 : 0;
}

function getMemberName(member) {
	const name = member.name;
	if (
		name
		&& (ts.isStringLiteral(name) || ts.isNumericLiteral(name) || ts.isIdentifier(name))
	) {
		return name.text;
	}
	return null;
}

function getNamedInterface(sourceFile, name) {
	return sourceFile.statements.find(
		(statement) => ts.isInterfaceDeclaration(statement) && statement.name.text === name,
	);
}

function getTypeLiteral(member) {
	return member && ts.isPropertySignature(member) && member.type && ts.isTypeLiteralNode(member.type)
		? member.type
		: null;
}

function getReferences(text, expression) {
	return [...text.matchAll(expression)].map((match) => match[1]);
}

function pascalCase(value) {
	return value
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.map((part) => part[0].toUpperCase() + part.slice(1))
		.join("");
}

function quoteTypeKey(value) {
	return `'${value.replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

function resolveDomain(apiPath) {
	const firstSegment = apiPath.split("/").filter(Boolean)[0];
	if (firstSegment && DOMAIN_OVERRIDES[firstSegment]) {
		return DOMAIN_OVERRIDES[firstSegment];
	}
	console.warn(
		`[split-api-types] Unrecognized API path "${apiPath}", assigning it to "${DEFAULT_DOMAIN}".`,
	);
	return DEFAULT_DOMAIN;
}

function addReference(target, reference) {
	if (!target.has(reference)) target.set(reference, new Set());
}

function collectFiles(directory, relativeDirectory = "") {
	if (!fs.existsSync(directory)) return [];
	return fs.readdirSync(directory, { withFileTypes: true })
		.sort((left, right) => compareStrings(left.name, right.name))
		.flatMap((entry) => {
			const relativePath = path.join(relativeDirectory, entry.name);
			const absolutePath = path.join(directory, entry.name);
			return entry.isDirectory()
				? collectFiles(absolutePath, relativePath)
				: [relativePath.split(path.sep).join("/")];
		});
}

function buildExpectedFiles() {
	if (!fs.existsSync(schemaPath)) {
		throw new Error(`OpenAPI schema not found: ${path.relative(rootDirectory, schemaPath)}`);
	}

	const sourceText = fs.readFileSync(schemaPath, "utf8");
	const schemaDigest = createHash("sha256").update(sourceText).digest("hex");
	const sourceFile = ts.createSourceFile(
		schemaPath,
		sourceText,
		ts.ScriptTarget.Latest,
		true,
		ts.ScriptKind.TS,
	);
	if (sourceFile.parseDiagnostics.length > 0) {
		const diagnostics = sourceFile.parseDiagnostics
			.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n"))
			.join("\n");
		throw new Error(`Unable to parse schema.d.ts:\n${diagnostics}`);
	}

	const pathsInterface = getNamedInterface(sourceFile, "paths");
	const operationsInterface = getNamedInterface(sourceFile, "operations");
	const componentsInterface = getNamedInterface(sourceFile, "components");
	if (!pathsInterface || !operationsInterface || !componentsInterface) {
		throw new Error("schema.d.ts must export paths, operations, and components interfaces.");
	}

	const pathsByDomain = new Map();
	const operationMembers = new Map(
		operationsInterface.members
			.map((member) => [getMemberName(member), member])
			.filter(([name]) => name !== null),
	);
	const operationSchemaReferences = new Map();
	const schemaReferences = new Map();
	const schemaMember = componentsInterface.members.find(
		(member) => getMemberName(member) === "schemas",
	);
	const schemasType = getTypeLiteral(schemaMember);
	if (!schemasType) {
		throw new Error('components["schemas"] must be a type literal in schema.d.ts.');
	}

	const schemaMembers = new Map(
		schemasType.members
			.map((member) => [getMemberName(member), member])
			.filter(([name]) => name !== null),
	);
	const schemaNames = [...schemaMembers.keys()].sort(compareStrings);

	for (const pathMember of pathsInterface.members) {
		const apiPath = getMemberName(pathMember);
		if (!apiPath) continue;

		const domain = resolveDomain(apiPath);
		if (!pathsByDomain.has(domain)) pathsByDomain.set(domain, []);
		pathsByDomain.get(domain).push(apiPath);

		for (const operationName of getReferences(pathMember.getText(sourceFile), OPERATION_REFERENCE)) {
			const operationMember = operationMembers.get(operationName);
			if (!operationMember) {
				throw new Error(`Path "${apiPath}" references unknown operation "${operationName}".`);
			}
			if (!operationSchemaReferences.has(domain)) {
				operationSchemaReferences.set(domain, new Set());
			}
			for (const schemaName of getReferences(operationMember.getText(sourceFile), SCHEMA_REFERENCE)) {
				if (!schemaMembers.has(schemaName)) {
					throw new Error(`Operation "${operationName}" references unknown schema "${schemaName}".`);
				}
				operationSchemaReferences.get(domain).add(schemaName);
			}
		}
	}

	for (const [schemaName, schemaMemberNode] of schemaMembers) {
		schemaReferences.set(
			schemaName,
			new Set(getReferences(schemaMemberNode.getText(sourceFile), SCHEMA_REFERENCE)),
		);
		for (const referencedName of schemaReferences.get(schemaName)) {
			if (!schemaMembers.has(referencedName)) {
				throw new Error(`Schema "${schemaName}" references unknown schema "${referencedName}".`);
			}
		}
	}

	const domainsForSchemas = new Map(schemaNames.map((name) => [name, new Set()]));
	for (const [domain, rootSchemas] of operationSchemaReferences) {
		const visited = new Set();
		const pending = [...rootSchemas];
		while (pending.length > 0) {
			const schemaName = pending.pop();
			if (visited.has(schemaName)) continue;
			visited.add(schemaName);
			domainsForSchemas.get(schemaName).add(domain);
			for (const referencedName of schemaReferences.get(schemaName)) {
				pending.push(referencedName);
			}
		}
	}

	const schemasByDomain = new Map();
	const sharedSchemas = [];
	for (const schemaName of schemaNames) {
		const owners = domainsForSchemas.get(schemaName);
		if (owners.size !== 1) {
			sharedSchemas.push(schemaName);
			continue;
		}
		const [owner] = owners;
		if (!schemasByDomain.has(owner)) schemasByDomain.set(owner, []);
		schemasByDomain.get(owner).push(schemaName);
	}

	const componentsMembers = componentsInterface.members.map(getMemberName).filter(Boolean);
	const unsupportedSections = componentsMembers.filter((name) => name !== "schemas").sort(compareStrings);
	if (unsupportedSections.length > 0) {
		console.warn(
			`[split-api-types] components has unsupported sections (not processed): ${unsupportedSections.join(", ")}`,
		);
	}

	const expectedFiles = new Map();
	const writeExpectedFile = (relativePath, contents) => {
		expectedFiles.set(relativePath, `${HEADER}\n// Source schema SHA-256: ${schemaDigest}\n${contents}`);
	};
	const generateComponents = (schemas) => {
		const imports = schemas.length > 0
			? "import type { components } from '../../schema';\n\n"
			: "";
		const aliases = schemas.map(
			(name) => `export type ${name} = components['schemas'][${quoteTypeKey(name)}];`,
		).join("\n");
		return `${imports}${aliases}${aliases ? "\n" : ""}`;
	};

	const domainNames = [...pathsByDomain.keys()].sort(compareStrings);
	for (const domain of domainNames) {
		const domainPaths = pathsByDomain.get(domain).sort(compareStrings);
		const pathTypeName = `${pascalCase(domain)}Paths`;
		const pathUnion = domainPaths.map(quoteTypeKey).join(" | ");
		const pathsSource = `import type { paths } from '../../schema';\n\nexport type ${pathTypeName} = Pick<paths, ${pathUnion}>;\n`;
		const ownedSchemas = schemasByDomain.get(domain) ?? [];
		const domainDirectory = domain;
		writeExpectedFile(
			`${domainDirectory}/paths.ts`,
			pathsSource,
		);
		writeExpectedFile(
			`${domainDirectory}/components.ts`,
			generateComponents(ownedSchemas),
		);
		writeExpectedFile(
			`${domainDirectory}/index.ts`,
			"export * from './paths';\nexport * from './components';\n",
		);
	}

	writeExpectedFile("shared/components.ts", generateComponents(sharedSchemas));

	return {
		domainNames,
		expectedFiles,
		pathsByDomain,
		schemasByDomain,
		sharedSchemas,
		unsupportedSections,
	};
}

function checkGeneratedFiles(expectedFiles) {
	const expectedPaths = [...expectedFiles.keys()].sort(compareStrings);
	const existingPaths = collectFiles(domainsPath);
	const allPaths = [...new Set([...expectedPaths, ...existingPaths])].sort(compareStrings);
	const differences = allPaths.filter((relativePath) => {
		if (!expectedFiles.has(relativePath)) return true;
		const absolutePath = path.join(domainsPath, ...relativePath.split("/"));
		return !fs.existsSync(absolutePath)
			|| fs.readFileSync(absolutePath, "utf8") !== expectedFiles.get(relativePath);
	});

	if (differences.length > 0) {
		console.error(`[split-api-types] Generated API types are out of date: ${differences.join(", ")}`);
		process.exitCode = 1;
		return false;
	}
	console.log("[split-api-types] Generated API types are up to date.");
	return true;
}

function writeGeneratedFiles(expectedFiles) {
	fs.rmSync(domainsPath, { recursive: true, force: true });
	for (const [relativePath, contents] of expectedFiles) {
		const absolutePath = path.join(domainsPath, ...relativePath.split("/"));
		fs.mkdirSync(path.dirname(absolutePath), { recursive: true });
		fs.writeFileSync(absolutePath, contents, "utf8");
	}
}

function printSummary({ domainNames, pathsByDomain, schemasByDomain, sharedSchemas }) {
	console.log("[split-api-types] Summary:");
	for (const domain of domainNames) {
		console.log(
			`  ${domain}: ${pathsByDomain.get(domain).length} paths, ${(schemasByDomain.get(domain) ?? []).length} domain schemas`,
		);
	}
	console.log(`  shared: ${sharedSchemas.length} schemas`);
	console.log(`  shared schemas: ${sharedSchemas.join(", ") || "(none)"}`);
}

try {
	const result = buildExpectedFiles();
	if (checkOnly) {
		checkGeneratedFiles(result.expectedFiles);
	} else {
		writeGeneratedFiles(result.expectedFiles);
		console.log(`[split-api-types] Generated ${result.expectedFiles.size} files in src/api/domains/.`);
	}
	printSummary(result);
} catch (error) {
	console.error(`[split-api-types] ${error instanceof Error ? error.message : String(error)}`);
	process.exitCode = 1;
}
